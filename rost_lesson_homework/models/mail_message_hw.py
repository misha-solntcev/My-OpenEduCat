from odoo import api, fields, models


class MailMessage(models.Model):
    """Связь сообщения в канале с заданием.

    Обратное поле к op.assignment.hw_channel_message_id. Нужно, чтобы при
    ленивом бэкфилле (пост найден по тексту, задание ещё без ссылки) можно
    было проверить: может, этот пост уже принадлежит другому заданию.

    Без такой проверки два одинаковых ДЗ в одном канале — «Домашка» у
    учителя самое частое — привели бы к тому, что правка одного задания
    переписывает объявление другого.
    """
    _inherit = 'mail.message'

    hw_assignment_ids = fields.One2many(
        'op.assignment', 'hw_channel_message_id',
        string='Задания ДЗ, ссылающиеся на это сообщение')