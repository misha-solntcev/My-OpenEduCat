# -*- coding: utf-8 -*-
"""Подписант договоров на уровне компании (меняется редко, но меняется:
доверенность 2021 -> 2026 в живых договорах)."""
from odoo import fields, models


class ResCompany(models.Model):
    _inherit = 'res.company'

    rost_director_name = fields.Char(
        'Директор: ФИО полностью',
        help="«Барановский Виктор Евгеньевич» — склоняется в документе "
             "автоматически (в лице кого).")
    rost_director_short = fields.Char(
        'Директор: ФИО кратко',
        help="«Барановский В.Е.» — для блока подписей.")
    rost_director_basis = fields.Char(
        'Директор: действует на основании',
        help="«Доверенности №1 от 26.04.2026» — в форме, в которой "
             "стоит в договоре.")
