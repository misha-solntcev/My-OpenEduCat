/**
 * Единый генератор инициалов для аватаров Mini App.
 * Берём ТОЛЬКО первую букву первого слова (единый формат для всех ролей:
 * админ, преподаватель, ученик) — иначе '?'.
 *
 * Раньше инициалы считались в двух местах по-разному (фронт для админа
 * давал до 2 букв, бэкенд для ученика — last+first), отсюда расхождение.
 * Теперь один источник правды на клиенте.
 */
export function initialsOf(name: string | undefined | null): string {
  const trimmed = (name || '').trim();
  if (!trimmed) return '?';
  return trimmed[0].toUpperCase();
}
